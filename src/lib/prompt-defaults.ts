/** 将模板中的 {{var}} 占位符替换为实际值 */
export function applyPromptVars(
  template: string,
  vars: Record<string, string>
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => vars[key] ?? "");
}

